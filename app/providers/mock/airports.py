def find_city(query: str) -> str | None:
    """把用户输入解析成城市名。

    支持四种命中方式，覆盖真实 autocomplete 的常见输入：
    IATA 三字码、精确城市名、别名（"蓉城"）、前缀/包含（"杭州市"、"去杭州"）。
    """
    text = (query or "").strip()
    if not text:
        return None

    if (airport := by_iata(text)) is not None:
        return airport.city
    if text in CITIES:
        return text
    if (alias := _ALIASES.get(text)) is not None:
        return alias

    # 包含匹配：优先最长的城市名，避免"南京"被"京"抢走
    for city in sorted(CITIES, key=len, reverse=True):
        if city in text:
            return city
    return None


def distance_km(a: MockAirport, b: MockAirport) -> float:
    """两机场间的大圆距离。只用于估价与估时长，不需要高精度。"""
    from app.core.geo import haversine_m

    return haversine_m((a.lng, a.lat), (b.lng, b.lat)) / 1000.0


