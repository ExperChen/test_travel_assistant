_BY_IATA: dict[str, MockAirport] = {a.iata: a for a in AIRPORTS}

CITIES: tuple[str, ...] = tuple(dict.fromkeys(a.city for a in AIRPORTS))
"""按 AIRPORTS 里的出现顺序去重，保证同城机场的主次顺序不被打乱。"""


def by_iata(code: str) -> MockAirport | None:
    return _BY_IATA.get((code or "").strip().upper())


def airports_of_city(city: str) -> list[MockAirport]:
    return [a for a in AIRPORTS if a.city == city]


# 常见的口语/别名 → 规范城市名。真实 autocomplete 对这些也能命中。
