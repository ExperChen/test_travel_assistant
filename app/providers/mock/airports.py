def city_center(city: str) -> tuple[float, float] | None:
    """市中心坐标 (lng, lat)，WGS-84。查不到时退回该城市主力机场。"""
    if (center := CITY_CENTERS.get(city)) is not None:
        return center
    airports = airports_of_city(city)
    return (airports[0].lng, airports[0].lat) if airports else None
